Student_Grade = int(input("What is your grade in this class? "))

if Student_Grade >= 90:
    print("You have an A!")
elif Student_Grade >= 80:
    print("You have a B")
elif Student_Grade >= 70:
    print("You have a C")
elif Student_Grade >= 60:
    print("You have a D")
else:
    print("You have a F")